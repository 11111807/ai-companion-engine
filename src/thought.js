/**
 * 思考：读消息时的"停顿感" + 她的内心想法（可折叠的那一块）。
 *
 * 用户的两条要求：
 *   1. 「语句输出如果太难理解的问题和对话可以多思考一两秒，增加真人的思考停顿感，
 *       但不要等待时间太长」
 *   2. 「给对话加上思考过程吧，把她的内心想法展示出来，用别的气泡做区分，
 *       可以下拉展开的」
 *
 * 关于第 2 条为什么**不用** API 的 reasoning_content：
 *   那是**模型的推理链**（"用户问了时间，我应该回答几点…"），不是"她的内心想法"。
 *   这里要的是角色本人的心里话（"他怎么突然问这个…"），所以让她按人设自己写，
 *   用隐藏块 `[[思考]]` 带回来 —— 和 `[[记忆]]` / `[[情绪]]` 是同一套做法，
 *   任何模型都能用，也能被单测钉住。
 *
 * 纯函数、零依赖，可以单独 import（见 test-modules.mjs）。
 */

// ---------------------------------------------------------------- 停顿感

/**
 * 「这句话值得多想一下」的信号。
 *
 * 注意都是**具体的结构**，不是"感觉难" —— 停顿本身要能解释，
 * 否则就成了随机变慢（用户会以为卡了）。
 */
const HARD_PATTERNS = [
  /为什么|怎么会|怎么办|该不该|要不要|是不是|会不会|值不值/u,   // 需要判断的
  /如果|假如|万一|要是/u,                                        // 假设
  /你觉得|你认为|你怎么看|你说呢/u,                              // 要她表态
  /记得|还记得|以前|当初|那时候|上次/u,                          // 要翻记忆
  /我们|你们|关系|喜欢|爱|分手|结婚|离开/u,                      // 分量重的
  /[？?].*[？?]/u,                                                // 一口气问了不止一个
];

/**
 * 他刚发的这句话，她大概要"想"多久（毫秒）。
 *
 * 上限刻意压到 1.6 秒：停顿是为了像人，不是为了让人等。
 * 太短的句子（"嗯""在吗"）不加 —— 那种也要想一下就很假。
 *
 * @param {string} text 他刚说的话
 * @param {object} [opts]
 * @param {number} [opts.max=1600] 上限
 * @returns {number} 毫秒（0 表示不停顿）
 */
export function thinkPause(text, { max = 1600 } = {}) {
  const t = String(text || '').trim();
  // 太短的不停：真人看到"在吗"不会先想两秒
  if (t.length < 8) return 0;

  let ms = 0;
  if (t.length >= 40) ms += 400;
  if (t.length >= 90) ms += 400;             // 长消息 = 要读一会儿
  const hits = HARD_PATTERNS.filter((re) => re.test(t)).length;
  ms += Math.min(2, hits) * 400;

  if (!ms) return 0;
  // 取整到 100ms，最多 max
  return Math.min(max, Math.round(ms / 100) * 100);
}

// ---------------------------------------------------------------- 内心想法

/** 她在回复里用来带"内心想法"的隐藏块（和 [[记忆]] / [[情绪]] 一个套路） */
const THOUGHT_HEAD = /\[\[\s*(?:思考|内心|心声)\s*\]\]/;

/**
 * 从她的回复里摘出内心想法，返回干净正文 + 想法本身。
 *
 * ⚠️ 为什么不用一条正则写完：`([\s\S]*?)(?=\s*$)` 这种写法会**一路吃到结尾**
 *    （懒惰量词找不到更早的落点，而"字符串末尾"永远满足前瞻）——
 *    结果是内心话把后面的台词全吞了。踩过，所以改成显式找结束位置：
 *    空行 / 下一个 `[[` / 字符串末尾，谁先到算谁。
 *
 * @param {string} text
 * @returns {{clean: string, thought: string}}
 */
export function parseThoughtBlock(text) {
  const src = String(text || '');
  const m = src.match(THOUGHT_HEAD);
  if (!m) return { clean: src, thought: '' };

  const tail = src.slice(m.index + m[0].length);
  const stops = [tail.search(/\n\s*\n/), tail.indexOf('[[')].filter((i) => i >= 0);
  const end = stops.length ? Math.min(...stops) : tail.length;

  // 一块内心话不该是篇小作文：多写了几行也只取前两行
  const thought = tail.slice(0, end)
    .split('\n').map((s) => s.trim()).filter(Boolean)
    .slice(0, 2).join(' ').slice(0, 120);

  // 整块擦干净（连它后面那段一起切掉），再收一下多余空行
  const clean = (src.slice(0, m.index) + src.slice(m.index + m[0].length + end))
    .replace(/\n{3,}/g, '\n\n').trim();
  return { clean, thought };
}

/**
 * 提示词里要求她写「思考」块的那一段（persona.js 会把它**独立**放进提示词）。
 *
 * ⚠️ 三个关键决定，都是踩出来的：
 *
 * 1. **放在【输出格式】旁边**。以前它孤零零排在提示词末尾，模型基本当没看见 ——
 *    用户的原话是"💭 思考 N 秒，我现在还是没有看到这个东西"。
 *    记忆块的要求一直写在输出格式这一带，所以它工作。
 *
 * 2. **"每一轮都要写"**，不是"没什么可想就整块不写"。
 *    上一版那句"可以不写"直接把遵守率打下去了 —— 这本来就是他要看见的东西。
 *
 * 3. ⭐ **和「情绪」块分开写，不能捆成"两块"**。用户的原话：
 *    「思考指的是讲下一句话时的内心想法，而不是有情绪才有思考」——
 *    捆在一起会让她以为"有情绪才有思考"，心情平淡时就不写了。
 *    内心是**每一句话都有**的：平静地想着"这菜有点咸"也是思考。
 */
export function thoughtPrompt() {
  return `【每一轮都要写：你的内心】（会折叠成"思考"，他点开才看得见）
在你要说的话**最前面**，另起一行写一块：
[[思考]]你对**下一句话**的内心独白

- 第一人称、20~50 字，写**心事**不写**动作** —— 动作写在（）里（那是旁白）
- ⭐ **它和情绪是两件事，也不靠情绪驱动**：不是"有情绪才有思考"。
  心情平平的时候你照样在想事情（"这菜有点咸""他今天话怎么这么少"），
  所以**每一轮都要有**，哪怕你只回一个"嗯"
- 它常常和你说出口的话**不一样**（嘴上"没事"，心里"有点介意"）——
  台词是他听见的，这一块是他点开才看见的
- 例：[[思考]]他又说"没事"了…我先别追问，顺着他说
- 反例（写成了动作，那是旁白的事）：把手机翻过来扣在桌上`;
}
