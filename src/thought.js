/**
 * 思考：读消息时的"停顿感" + 她的内心想法（可折叠的那一块）。
 *
 * 用户的两条要求：
 *   1. 「语句输出如果太难理解的问题和对话可以多思考一两秒，增加真人的思考停顿感，
 *       但不要等待时间太长」
 *   2. 「给对话加上思考过程吧，把她的内心想法展示出来，用别的气泡做区分，
 *       可以下拉展开的」
 *
 * 关于第 2 条为什么**不用** API 的 reasoning_content：
 *   那是**模型的推理链**（"用户问了时间，我应该回答几点…"），不是"她的内心想法"。
 *   这里要的是角色本人的心里话（"他怎么突然问这个…"），所以让她按人设自己写，
 *   用隐藏块 `[[思考]]` 带回来 —— 和 `[[记忆]]` / `[[情绪]]` 是同一套做法，
 *   任何模型都能用，也能被单测钉住。
 *
 * 纯函数、零依赖，可以单独 import（见 test-modules.mjs）。
 */

// ---------------------------------------------------------------- 停顿感

/**
 * 「这句话值得多想一下」的信号。
 *
 * 注意都是**具体的结构**，不是"感觉难" —— 停顿本身要能解释，
 * 否则就成了随机变慢（用户会以为卡了）。
 */
const HARD_PATTERNS = [
  /为什么|怎么会|怎么办|该不该|要不要|是不是|会不会|值不值/u,   // 需要判断的
  /如果|假如|万一|要是/u,                                        // 假设
  /你觉得|你认为|你怎么看|你说呢/u,                              // 要她表态
  /记得|还记得|以前|当初|那时候|上次/u,                          // 要翻记忆
  /我们|你们|关系|喜欢|爱|分手|结婚|离开/u,                      // 分量重的
  /[？?].*[？?]/u,                                                // 一口气问了不止一个
];

/**
 * 他刚发的这句话，她大概要"想"多久（毫秒）。
 *
 * 上限刻意压到 1.6 秒：停顿是为了像人，不是为了让人等。
 * 太短的句子（"嗯""在吗"）不加 —— 那种也要想一下就很假。
 *
 * @param {string} text 他刚说的话
 * @param {object} [opts]
 * @param {number} [opts.max=1600] 上限
 * @returns {number} 毫秒（0 表示不停顿）
 */
export function thinkPause(text, { max = 1600 } = {}) {
  const t = String(text || '').trim();
  // 太短的不停：真人看到"在吗"不会先想两秒
  if (t.length < 8) return 0;

  let ms = 0;
  if (t.length >= 40) ms += 400;
  if (t.length >= 90) ms += 400;             // 长消息 = 要读一会儿
  const hits = HARD_PATTERNS.filter((re) => re.test(t)).length;
  ms += Math.min(2, hits) * 400;

  if (!ms) return 0;
  // 取整到 100ms，最多 max
  return Math.min(max, Math.round(ms / 100) * 100);
}

// ---------------------------------------------------------------- 内心想法

/**
 * 她在回复里用来带"内心想法"的隐藏块（和 [[记忆]] / [[情绪]] 一个套路）。
 *
 * ⚠️ 两个容错，都是实测踩出来的：
 *   1. **必须在行首**（行首或换行之后）。不加这个限制的话，台词里偶然出现的
 *      `[思考]` 也会被当成块头，把后面的正文全吃掉。
 *   2. **单括号也认**：模型偶尔只写一个 `[思考]`，不认的话这一块会原样留在
 *      台词里（虽然 stripLabel 能剥掉标签，但那句话就变成台词了）。
 */
const THOUGHT_HEAD = /(?:^|\n)[ \t]*\[\[?[ \t]*(?:思考|内心|心声)[ \t]*\]\]?/;

/**
 * 从她的回复里摘出内心想法，返回干净正文 + 想法本身。
 *
 * ⚠️ 为什么不用一条正则写完：`([\s\S]*?)(?=\s*$)` 这种写法会**一路吃到结尾**
 *    （懒惰量词找不到更早的落点，而"字符串末尾"永远满足前瞻）——
 *    结果是内心话把后面的台词全吞了。踩过，所以改成显式找结束位置：
 *    空行 / 下一个 `[[` / 字符串末尾，谁先到算谁。
 *
 * ⚠️⚠️ **没有空行时必须退一步只取一行**（用户实测："对话内容跑到思考框里去了"）：
 *    提示词里写的是"在你要说的话最前面，另起一行写一块"，模型经常就**只用一个换行**
 *    分隔内心和台词：
 *      `[[思考]]他怎么突然问这个…\n在忙呢，刚看到`
 *    这时如果按"到末尾"算，**整段台词都会被当成内心吞掉** —— 思考框里出现对话内容，
 *    而台词变成空的（还会触发"只发旁白"之类的兜底）。
 *    所以没有空行时，只认**第一行有内容的行**是内心，其余留给台词。
 *
 *    代价：如果她内心写了两行、又没用空行收尾，第二行会被当成台词说出来。
 *    这个没法两全（模型没给分隔符），但"少说错一句"远好过"整段台词消失"。
 *
 * @param {string} text
 * @returns {{clean: string, thought: string}}
 */
export function parseThoughtBlock(text) {
  const src = String(text || '');
  const m = src.match(THOUGHT_HEAD);
  if (!m) return { clean: src, thought: '' };

  const body = src.slice(m.index + m[0].length);
  const blank = body.search(/\n\s*\n/);
  const stops = [blank, body.indexOf('[[')].filter((i) => i >= 0);
  let end = stops.length ? Math.min(...stops) : body.length;

  // 没有空行 → 只取第一行有内容的行（见上面那段说明）
  if (blank < 0) {
    const lines = body.split('\n');
    let used = 0;
    for (let i = 0; i < lines.length; i++) {
      used += lines[i].length + (i ? 1 : 0);
      if (lines[i].trim()) { end = used; break; }
    }
  }

  // 一块内心话不该是篇小作文：多写了几行也只取前两行
  const thought = body.slice(0, end)
    .split('\n').map((s) => s.trim()).filter(Boolean)
    .slice(0, 2).join(' ').slice(0, 120);

  // 整块擦干净（连它后面那段一起切掉），再收一下多余空行
  const clean = (src.slice(0, m.index) + src.slice(m.index + m[0].length + end))
    .replace(/\n{3,}/g, '\n\n').trim();
  return { clean, thought };
}

/**
 * 提示词里要求她写「思考」块的那一段（persona.js 会把它**独立**放进提示词）。
 *
 * ⚠️ 三个关键决定，都是踩出来的：
 *
 * 1. **放在【输出格式】旁边**。以前它孤零零排在提示词末尾，模型基本当没看见 ——
 *    用户的原话是"💭 思考 N 秒，我现在还是没有看到这个东西"。
 *    记忆块的要求一直写在输出格式这一带，所以它工作。
 *
 * 2. **"每一轮都要写"**，不是"没什么可想就整块不写"。
 *    上一版那句"可以不写"直接把遵守率打下去了 —— 这本来就是他要看见的东西。
 *
 * 3. ⭐ **和「情绪」块分开写，不能捆成"两块"**。用户的原话：
 *    「思考指的是讲下一句话时的内心想法，而不是有情绪才有思考」——
 *    捆在一起会让她以为"有情绪才有思考"，心情平淡时就不写了。
 *    内心是**每一句话都有**的：平静地想着"这菜有点咸"也是思考。
 *
 * 4. ⭐ **要"灵动"，不能给一个句式模板**。用户的原话：
 *    「思考内容要灵动一点，每次都是，心里挺受用的，思考也不能太机械了，像人一样」。
 *    上一版给了一条示例（"他又说没事了…我先别追问，顺着他说"），
 *    结果模型每轮都照着这个**策略腔句式**套 —— 一眼就是机器。
 *    所以这一版改成**列几个不同的想事情角度**，并明确点名禁止那种写法。
 */
export function thoughtPrompt() {
  return `【每一轮都要写：你的内心】（会折叠成"思考"，他点开才看得见）
在你要说的话**最前面**写一块，写成这样：

[[思考]]你对**下一句话**的内心独白

（这里**空一行**，然后才是你要说的话）

⚠️ **两处格式必须照做**（实测最容易错的就是这个）：
1. 这一块**只占一行**
2. 它后面**必须空一行**，再写你要说的话。
   只用一次换行的话，界面会把你的**台词也当成内心**折进去 —— 他就看不见你说的话了

- 第一人称、10~50 字，写**心事**不写**动作** —— 动作写在（）里（那是旁白）
- ⭐ **想的是"此刻"**：他刚说的这句话、你手上正在做的事、你眼前的场景。
  **别连着几轮都惦记同一件事**（用户点过名：心里反复念"明天要早起"这种，很出戏）
- ⭐ **它和情绪是两件事，也不靠情绪驱动**：不是"有情绪才有思考"。
  心情平平的时候你照样在想事情（"这菜有点咸""他今天话怎么这么少"），
  所以**每一轮都要有**，哪怕你只回一个"嗯"
- 它常常和你说出口的话**不一样**（嘴上"没事"，心里"有点介意"）——
  台词是他听见的，这一块是他点开才看见的

⭐ **要像人，别每次都一个句式**（最容易翻车的一条）：
真人心里那一下是**跳的、短的、甚至不成句**的，不是每次都"他…了，我应该…"。
每一轮**换一个角度**，下面这些轮着来：

- 第一反应：\`啊？怎么突然问这个\`、\`诶，他居然记得\`
- 心里的小得意 / 小别扭：\`哼，现在想起我了\`、\`他这么一说我还挺受用的\`
- 联想到自己：\`我上次也是这样，最后没敢说\`
- 犹豫要不要说：\`要不要问他呢…算了，先不说这个\`
- 走神 / 自我吐槽：\`我是不是想太多了\`、\`我这脑子\`
- 对下一句话的小打算：\`待会儿得问问后来怎么样了\`

⚠️ **写成下面这样等于没写**（一眼就是机器）：
- 策略腔、像在汇报：\`他在问我时间，我应该回答几点\`、\`我需要先安抚他\`
- 每轮都是同一个句式：\`他又说没事了…我先别追问，顺着他说\`
- 把他说的话复述一遍，或者把台词在这里再写一遍
- 表决心、讲道理、总结：\`我决定要好好陪他\`、\`陪伴是最重要的\`
- 写成动作（那是旁白的事）：\`把手机翻过来扣在桌上\`

允许半句话、允许口语、允许只有几个字：\`诶？\`、\`…有点想他了\`。`;
}

// ---------------------------------------------------------------- 别写重样
//
// 和旁白那套一模一样（见 narration.js）：光说"别机械"没有用，
// 得把她**最近几次真写过什么**摆回去 —— 模型看不见自己前面写了什么，
// 没人点名它就会一直用同一个句式（用户的原话就是"每次都是"）。

/**
 * 她最近几次的内心（去重、从旧到新）。
 * @param {Array<{role:string,think?:string}>} msgs
 * @param {object} [opts]
 * @param {number} [opts.recentN=80] 只看最近多少条消息
 * @param {number} [opts.max=6]      最多列几条
 * @returns {string[]}
 */
export function recentThoughts(msgs, { recentN = 80, max = 6 } = {}) {
  const list = Array.isArray(msgs) ? msgs.slice(-recentN) : [];
  const seen = new Set();
  const out = [];
  for (const m of list) {
    if (m?.role !== 'assistant' || !m.think) continue;   // 内心挂在她的第一条消息上
    const t = String(m.think).trim();
    if (!t || seen.has(t)) continue;
    seen.add(t);
    out.push(t);
  }
  return out.slice(-max);
}

/**
 * 把"最近几次的内心"拼成提示词里的一段。
 * 一次都没写过就返回空串（新用户别塞一段空的进提示词）。
 * @param {string[]} list
 */
export function thoughtVaryBlock(list = []) {
  const items = (Array.isArray(list) ? list : []).map((s) => String(s || '').trim()).filter(Boolean);
  if (!items.length) return '';
  return `【你最近几次的内心】（别再来一遍）
${items.map((s) => `- ${s}`).join('\n')}

上面这些是**你前几轮想过的东西**。这一轮：
- 别再写同一个意思、同一个句式（"他…了，我先…"这种连着出现两次就很假）
- 换个角度想：第一反应 / 联想到自己 / 犹豫 / 走神 / 小得意，挑一个跟上面不一样的
- ⭐ **也别反复惦记同一件事**。上面几条要是在想同一桩（比如连着几次都在担心
  "明天要早起"），这一轮就把它放下 —— 想**当下的**：他刚说的这句话本身、
  你手上正在做的事、你眼前的这个场景（用户说过：心里反复念同一件事，很出戏）
- 也别为了不一样硬编 —— 真的没什么想法，就写一句短短的当下感受（"有点困了"）`;
}
