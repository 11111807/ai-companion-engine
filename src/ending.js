/**
 * 终局检测：他在**旁白**里写了"你们一起老去/都死了"这类话时，先问一句再动手。
 *
 * 用户要的流程（原话）：
 *   「如果用户输出旁白说两人过了很多年，一起死亡了，这种话……弹窗警告，
 *     是否忘记你们的一切（删档），是用灰色，否用绿色；
 *     如果选择是，弹窗再弹一遍，是用灰色，和"我还没想好"用绿色；
 *     如果再选择是，就删除；如果选择否/"我还没想好"，就取消弹窗回到聊天框，
 *     并注明旁白（你们都睡着了，做了一个好梦，白天醒来又是美好的一天）」
 *
 * 为什么要专门做这个（而不是直接删或直接不管）：
 *   这种旁白在**剧情**上等于给这段关系画了句号。要么他真想收尾（那就清干净、
 *   从头开始），要么只是一时入戏（那得给个台阶 —— 把刚才那段解释成一场梦）。
 *   最糟的是不闻不问：她会带着"我们都已经死了"继续跟他聊今天晚饭吃什么。
 *
 * 纯函数、零依赖。误判的代价说明：**宁可漏，不可误**——
 * 把"笑死我了""累死了"当成终局会突然弹窗打断正常聊天，那比漏判难受得多。
 */

/**
 * 什么才算"终局"：**必须真的有死亡语义**。
 *
 * ⚠️ 这条规则被用户纠过一次，原话是：
 *   「这个死亡判定太笼统了，写个"一起走了出去"也能判定吗？
 *     不应该核心判断是**至少一方死亡**吗」
 *   他说得对 —— 上一版词表里有 `一起(老去|变老|白头)` 和 `(都|一起)(…|走)了`，
 *   于是「（我们一起走了出去）」「（他们白头到老）」都会弹"是否忘记你们的一切"。
 *   现在**只认明确的死亡词**（或"死"字本身 + 明确的生离死别语境），
 *   "一起老去""白头到老""走了""很多年后"这些**一律不判**。
 *
 * 误判的代价：突然弹窗打断正常聊天，比漏判难受得多 —— **宁可漏，不可误**。
 */
const DEATH_WORDS = [
  '去世', '离世', '过世', '逝世', '身亡', '牺牲', '长眠', '安息',
  '咽气', '断气', '弥留', '临终', '病逝', '夭折', '离开人世', '不在人世',
  '离开这个世界', '离开了这个世界', '离开了人世', '离开了我们',
  '最后一面', '葬礼', '墓碑', '坟前', '墓前', '忌日', '遗照', '遗像', '骨灰',
];

/**
 * 单个"死"字要不要算 —— 中文里它几乎全是夸张用法
 *（"笑死我了""累死了""想死你了""无聊死了"），
 * 所以**必须有人称或"一起/双双/都"紧挨着**才算："她死了""都死了""一起死了"。
 * 光写 `死[了去]` 会把"累死了"也算进来（测试当场抓到了这条）。
 */
const DEATH_STRICT = /(?:(?:她|他|我|你|我们|两人|两个人|双双|一起|都)\s*死[了去]|死别|生死(?:离别|相隔))/;

/**
 * 会把它当成"终局"的语境 —— 必须是**旁白**（他在描述剧情），
 * 台词里说"我们一起老去"更像情话，不该弹窗。
 */
/**
 * 会把它当成"终局"的语境 —— 必须是**旁白**（他在描述剧情），
 * 台词里说"我们一起老去"更像情话，不该弹窗。
 *
 * @returns {string} 命中的那个词（空串 = 不算终局）
 */
export function detectEnding(text, { narr = false } = {}) {
  const t = String(text || '').trim();
  if (!t) return '';
  // 只在旁白里判：他自己说的话（"我要跟你过一辈子"）是表白，不是结局
  if (!narr) return '';
  // 1) 明确的死亡词（"她去世了""葬礼那天"）
  const hit = DEATH_WORDS.find((w) => t.includes(w));
  if (hit) return hit;
  // 2) 单个"死"字：只认那些明确搭配，别把"笑死我了"当终局
  const m = t.match(DEATH_STRICT);
  return m ? m[0] : '';
}

