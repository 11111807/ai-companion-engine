/**
 * 终局检测：他在**旁白**里写了"你们一起老去/都死了"这类话时，先问一句再动手。
 *
 * 用户要的流程（原话）：
 *   「如果用户输出旁白说两人过了很多年，一起死亡了，这种话……弹窗警告，
 *     是否忘记你们的一切（删档），是用灰色，否用绿色；
 *     如果选择是，弹窗再弹一遍，是用灰色，和"我还没想好"用绿色；
 *     如果再选择是，就删除；如果选择否/"我还没想好"，就取消弹窗回到聊天框，
 *     并注明旁白（你们都睡着了，做了一个好梦，白天醒来又是美好的一天）」
 *
 * 为什么要专门做这个（而不是直接删或直接不管）：
 *   这种旁白在**剧情**上等于给这段关系画了句号。要么他真想收尾（那就清干净、
 *   从头开始），要么只是一时入戏（那得给个台阶 —— 把刚才那段解释成一场梦）。
 *   最糟的是不闻不问：她会带着"我们都已经死了"继续跟他聊今天晚饭吃什么。
 *
 * 纯函数、零依赖。误判的代价说明：**宁可漏，不可误**——
 * 把"笑死我了""累死了"当成终局会突然弹窗打断正常聊天，那比漏判难受得多。
 */

/**
 * 明确表示"这段关系走到了尽头"的说法。
 *
 * 都是**成句**的词，不收单字（"死"这个字在中文里大量用于夸张，
 * 和 affection.js 里不把单字"滚""烦死"当伤人话是同一个道理）。
 */
const ENDING_PATTERNS = [
  /一起(老去|变老|白头|走到最后)/u,
  /(都|一起|双双)(死|去世|离开|走)了/u,
  /(死|去世|离世|过世|走了|没了)之后/u,
  /(临终|弥留|最后一面|葬礼|墓前|墓碑|坟前)/u,
  /(这辈子|一生|一生一世|一辈子).{0,6}(结束|过完|走完)/u,
  /(结束|告别|说再见).{0,4}(这(一)?(生|世)|这段)/u,
  /(很多年|几十年|多年)后.{0,10}(都|一起)?(老|死|走|离开)/u,
  /(白发苍苍|老得走不动|生命(的)?最后)/u,
];

/**
 * 会把它当成"终局"的语境 —— 必须是**旁白**（他在描述剧情），
 * 台词里说"我们一起老去"更像情话，不该弹窗。
 */
export function detectEnding(text, { narr = false } = {}) {
  const t = String(text || '').trim();
  if (!t) return '';
  // 只在旁白里判：他自己说的话（"我要跟你过一辈子"）是表白，不是结局
  if (!narr) return '';
  // 太长的旁白多半是在写剧情细节，也算 —— 但极短的一句"（死了）"也算，所以不设下限
  for (const re of ENDING_PATTERNS) {
    const m = t.match(re);
    if (m) return m[0];
  }
  return '';
}

